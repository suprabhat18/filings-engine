"use client";

import { signIn, useSession } from "next-auth/react";

export default function RequireSignIn({ children }: { children: React.ReactNode }) {
  const { data: session, status } = useSession();

  if (status === "loading") {
    return <p className="muted" role="status">Checking your sign-in…</p>;
  }

  if (status !== "authenticated" || session.error) {
    return (
      <div className="intro-layout">
      <section className="intro">
        <h1 className="intro__title">Ask the filings.</h1>
        <p className="intro__lede">
          Questions in any language, answered from the 10-K, 10-Q and 8-K filings of S&amp;P 100
          companies. Every claim links back to the passage it came from.
        </p>
        {session?.error && <p className="notice">Your session expired. Sign in again to continue.</p>}
        <button type="button" className="btn btn--primary" onClick={() => signIn("google")}>
          Sign in with Google
        </button>
        <p className="fine-print">
          Signing in keeps your watchlist, bookmarks and search history. Filings come from SEC
          EDGAR and are updated regularly. Answers are generated by AI and can be wrong; check the
          cited sources.
        </p>
      </section>

      <figure className="specimen" aria-label="Example of an answer with a citation">
        <p className="specimen__q">What does Apple say about where its products are made?</p>
        <p className="specimen__a">
          Most of Apple’s hardware is built by outsourcing partners in China mainland, India,
          Japan, South Korea, Taiwan and Vietnam, and much of it by a small number of partners,
          often in single locations
          <span className="cite-group">
            <span className="cite cite--static" aria-hidden="true">1</span>.
          </span>
        </p>
        <figcaption className="specimen__source">
          <span className="specimen__n">1</span>
          <span>
            <strong>Apple Inc.</strong> 10-K, Item 1A. Risk Factors
            <span className="specimen__quote">
              “Substantially all of the Company’s hardware products are manufactured by
              outsourcing partners…”
            </span>
          </span>
        </figcaption>
      </figure>
      </div>
    );
  }

  return <>{children}</>;
}
